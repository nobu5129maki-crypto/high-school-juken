export function monthAdvice(pref: string) {
  if (pref === '東京都') {
    return '都立は換算内申（5科×2＋実技）と学力検査。2月下旬の一般に向け、私立先行が基本です。'
  }
  if (pref === '神奈川県') {
    return '内申は中2・中3の積み上げ。特色検査のある学校は記述の練習を秋から。'
  }
  if (pref === '愛知県') {
    return '複合選抜・群制度を中学校で確認。名古屋の私立との併願が一般的です。'
  }
  if (pref === '大阪府' || pref === '京都府' || pref === '兵庫県') {
    return '関西は私立が2月上旬、公立が後半。制度変更の年は募集要項を必ず最新で。'
  }
  return '私立は1〜2月、公立は2〜3月が目安。都道府県で全く違うので、必ず教育委員会の要項を見てください。'
}
