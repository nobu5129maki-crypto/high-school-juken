function withCoverage(list: School[]): School[] {
  const extras: School[] = []
  const prefs = [...new Set(list.map((s) => s.prefecture))]
  for (const pref of prefs) {
    // 寮のある私立は全国向けの候補なので、地域の中堅・実業校の有無判定からは外す
    const local = list.filter((s) => s.prefecture === pref && !s.dorm)
    if (local.length === 0) continue
    const city = local[0].city
    const dateKey = local.find((s) => s.kind === '公立')?.dateKey ?? 'public-mar'
    const shortCity = city.replace(/[市区]$/, '')
    if (!local.some((s) => s.hensachi <= 58 && s.course.includes('普通'))) {
      extras.push(
        toSchool({
          id: `${pref}-mid-ordinary`,
          name: `${shortCity}みらい高等学校（モデル）`,
          prefecture: pref,
          city,
          kind: '公立',
          course: '普通科',
          hensachi: 52,
          commuteMin: Math.min(40, (local[0].commuteMin || 30) + 5),
          clubs: ['サッカー', '吹奏楽', 'ボランティア'],
          features: ['中堅公立', 'バランス', '地域密着'],
          atmosphere: ['穏やか', '生活'],
          tags: ['通学', '学費', '校風'],
          university: '地元国公立・中堅私大・専門学校まで幅広い。',
          examStyle: '学力検査＋内申',
          examSeason: '公立一般（地域の日程）',
          dateKey,
          description: `${pref}の中堅公立普通科を合成したモデル校です。最難関だけが「合う高校」ではありません。`,
          teacherNote: '安全校は「行きたくない学校」にしないこと。本人が通う姿を想像できるかが大切です。',
          jukuNote: 'チャレンジ校を1つ置くなら、この帯の学校を本命または安全に必ず入れる。',
          studentNote: '友達もできやすく、部活も勉強も両立しやすいタイプです。',
          model: true,
        }),
      )
    }
    if (!local.some((s) => s.tags.includes('専門スキル'))) {
      extras.push(
        toSchool({
          id: `${pref}-vocational`,
          name: `${shortCity}実業高等学校（モデル）`,
          prefecture: pref,
          city,
          kind: '公立',
          course: '総合・実業（商業／工業／農業など）',
          hensachi: 47,
          commuteMin: Math.min(45, (local[0].commuteMin || 30) + 8),
          clubs: ['ものづくり', '情報', 'バスケ'],
          features: ['資格', '実習', '就職にも強い'],
          atmosphere: ['実学', 'チーム'],
          tags: ['専門スキル', '学費'],
          university: '専門・就職・大学進学の三本柱。',
          examStyle: '学力検査＋面接（学科による）',
          examSeason: '公立一般（地域の日程）',
          dateKey,
          description: `${pref}の実業・総合高校を合成したモデル校。手を動かす学びが好きな人に。`,
          teacherNote: '普通科に届かないから実業、という決め方はしないでください。適性が先です。',
          jukuNote: '学科見学必須。商業・工業・農業・福祉で適性は全く違います。',
          studentNote: '授業が「将来の仕事」に近く、やる気が出やすいです。',
          model: true,
        }),
      )
    }
  }
  return [...list, ...extras]
}

export const SCHOOLS: School[] = withCoverage([...seeds, ...dormSeeds, ...majorSeeds].map(toSchool))

